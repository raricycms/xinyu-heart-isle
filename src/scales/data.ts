/** 全部量表。顺序即默认展示顺序。 */
export const SCALES: Scale[] = [PHQ9, GAD7, PSS10, ISI, RSES];

/** 按 id 取量表，找不到返回 undefined。 */
export function getScaleById(id: string): Scale | undefined {
  return SCALES.find((scale) => scale.id === id);
}

/**
 * 作答页在题干下方的追问句。
 *
 * 各量表的选项维度不同（频率 / 严重程度 / 符合程度），
 * 统一写「出现频率」会在 ISI、RSES 上出现语病，因此按量表给专用措辞。
 */
const ANSWER_PROMPTS: Record<string, string> = {
  'phq-9': '最近两周内，这种情况出现的频率是：',
  'gad-7': '最近两周内，这种情况出现的频率是：',
  'pss-10': '过去一个月里，这种情况出现的频率是：',
  'isi-7': '最近两周，这个问题对你的严重程度是：',
  'rses-10': '这句话和此刻的你，符合程度是：',
};

/** 取某量表的作答追问句，未知量表给一个中性兜底。 */
export function answerPrompt(scale: Scale): string {
  return ANSWER_PROMPTS[scale.id] ?? '请选择最接近你情况的一项：';
}


/** 出现在数据里的分类（保持首次出现顺序），供筛选器使用。 */
